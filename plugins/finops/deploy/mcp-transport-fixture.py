"""Synthetic, dependency-free stdio MCP fixture for the sandbox transport gate.

This diagnostic server has no Azure credentials, filesystem tools or network access.
Its random bytes must be read from saved tool output, never regenerated by the agent.
"""

import base64
import hashlib
import json
import secrets
import sys


TOOL_NAME = "read_transport_fixture"
SIZES = (1024, 262144, 1048576)
PROTOCOLS = ("2024-11-05", "2025-03-26", "2025-06-18")


def _error(request_id, code, message):
    return {"jsonrpc": "2.0", "id": request_id,
            "error": {"code": code, "message": message}}


def handle(request):
    if not isinstance(request, dict) or request.get("jsonrpc") != "2.0":
        return _error(None, -32600, "Invalid JSON-RPC request")
    if "id" not in request:
        return None
    request_id = request["id"]
    method = request.get("method")
    params = request.get("params", {})
    if not isinstance(params, dict):
        return _error(request_id, -32602, "Parameters must be an object")
    if method == "initialize":
        version = params.get("protocolVersion")
        result = {
            "protocolVersion": version if version in PROTOCOLS else PROTOCOLS[-1],
            "capabilities": {"tools": {"listChanged": False}},
            "serverInfo": {"name": "finops-transport-fixture", "version": "1.0.0"},
        }
    elif method == "ping":
        result = {}
    elif method == "tools/list":
        result = {"tools": [{
            "name": TOOL_NAME,
            "description": "Return bounded synthetic random bytes to verify saved MCP tool output.",
            "inputSchema": {
                "type": "object",
                "properties": {"size": {"type": "integer", "enum": list(SIZES)}},
                "required": ["size"],
                "additionalProperties": False,
            },
            "annotations": {
                "readOnlyHint": True, "destructiveHint": False,
                "idempotentHint": False, "openWorldHint": False,
            },
        }]}
    elif method == "tools/call":
        arguments = params.get("arguments")
        if (params.get("name") != TOOL_NAME or not isinstance(arguments, dict)
                or set(arguments) != {"size"} or type(arguments["size"]) is not int
                or arguments["size"] not in SIZES):
            return _error(request_id, -32602, "Select the fixture tool and an allowed size")
        raw = secrets.token_bytes(arguments["size"])
        payload = {
            "fixture": "finops-mcp-transport-v1",
            "byte_count": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
            "payload_base64": base64.b64encode(raw).decode("ascii"),
        }
        result = {"content": [{"type": "text", "text": json.dumps(payload)}],
                  "isError": False}
    else:
        return _error(request_id, -32601, "Method not supported by this diagnostic fixture")
    return {"jsonrpc": "2.0", "id": request_id, "result": result}


def main():
    for line in sys.stdin:
        try:
            request = json.loads(line)
        except json.JSONDecodeError:
            response = _error(None, -32700, "Invalid JSON")
        else:
            response = handle(request)
        if response is not None:
            print(json.dumps(response, separators=(",", ":")), flush=True)


if __name__ == "__main__":
    main()
